'use strict';
// Generates docs/API.md from the registered routes. Usage: node scripts/gen-api-docs.js
process.env.SUDS_ENV = process.env.SUDS_ENV || 'test'; process.env.SUDS_DB_PATH = ':memory:';
const fs = require('node:fs');
const { Router } = require('../server/http');
const r = new Router();
for (const mod of ['auth', 'users', 'clients', 'assignments', 'interventions', 'calls', 'time', 'resources', 'referrals', 'tasks', 'budget', 'notes', 'consents', 'imports', 'reports', 'admin', 'intake']) require(`../server/routes/${mod}`)(r);
const rows = r.routes.map(x => {
  let i = 0;
  const path = x.re.source.replace(/^\^/, '').replace(/\\\/\?\$$/, "").replace(/\(\[\^\/\]\+\)/g, () => ':' + x.keys[i++]).replace(/\\\//g, '/');
  return { method: x.method, path };
});
const groups = {};
for (const x of rows) { const g = x.path.split('/')[2]; (groups[g] = groups[g] || []).push(x); }
let out = `# SUDS REST API

All endpoints are under \`/api\`. Authentication is a session cookie set by \`POST /api/auth/login\` (browser) or an \`Authorization: Bearer <session token>\` header; state-changing requests from a cookie session must include \`X-Requested-With: suds\`. Intake endpoints use an API key. Responses are JSON; errors are \`{ error, fields? }\`. List endpoints accept \`limit\`, \`offset\`, \`client_id\`, \`from\`, \`to\`, \`mine=1\` and \`user_id\` where applicable. Every PHI access is audited.

Permissions per role are defined in \`server/auth.js\` (\`PERMS\`). Generated by \`scripts/gen-api-docs.js\`.
`;
for (const [g, list] of Object.entries(groups)) { out += `\n## ${g}\n\n| Method | Path |\n| --- | --- |\n`; for (const x of list) out += `| ${x.method} | \`${x.path}\` |\n`; }
out += `
## Intake payload (Pocket AI)

\`\`\`
POST /api/intake/notes
Authorization: Bearer suds_<key>
Content-Type: application/json

{ "title": "...", "transcript": "...", "summary": "...", "action_items": ["..."], "created_at": "2026-09-10T15:04:00Z", "tags": ["field"] }
\`\`\`

A JSON array or \`{ "notes": [...] }\` is also accepted. Response: \`202 { import_id, staged }\`.

## Break-glass

Administrators may read a clinical note by sending \`X-Break-Glass-Reason: <reason>\` with \`GET /api/notes/:id\`; the access and reason are written to the audit log.
`;
fs.writeFileSync(require('node:path').join(__dirname, '..', 'docs', 'API.md'), out);
console.log(`${rows.length} routes documented`);
