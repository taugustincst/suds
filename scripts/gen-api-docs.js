'use strict';
// Generates docs/API.md from the registered routes. Usage: node scripts/gen-api-docs.js
process.env.SUDS_ENV = process.env.SUDS_ENV || 'test'; process.env.SUDS_DB_PATH = ':memory:';
const fs = require('node:fs');
const { Router } = require('../server/http');
const r = new Router();
// The module list lives in server/app.js; a copy here is how docs come to describe a version of the API
// that no longer exists.
for (const mod of require('../server/app').ROUTE_MODULES) require(`../server/routes/${mod}`)(r);
const rows = r.routes.map(x => {
  let i = 0;
  const path = x.re.source.replace(/^\^/, '').replace(/\\\/\?\$$/, "").replace(/\(\[\^\/\]\+\)/g, () => ':' + x.keys[i++]).replace(/\\\//g, '/').replace(/\\([$.])/g, '$1');
  return { method: x.method, path };
});
const groups = {};
// The FHIR API lives under /fhir/R4, not /api; it is listed as one group and described in docs/integration/FHIR.md.
for (const x of rows) { const g = x.path.startsWith('/fhir/') ? 'fhir (FHIR R4, read-only — see docs/integration/FHIR.md)' : x.path.split('/')[2]; (groups[g] = groups[g] || []).push(x); }
let out = `# SUDS REST API

All endpoints are under \`/api\`. Authentication is a session cookie set by \`POST /api/auth/login\` (browser) or an \`Authorization: Bearer <session token>\` header; state-changing requests from a cookie session must include \`X-Requested-With: suds\`. Intake endpoints use an API key. Responses are JSON; errors are \`{ error, fields? }\`. List endpoints accept \`limit\`, \`offset\`, \`client_id\`, \`from\`, \`to\`, \`mine=1\` and \`user_id\` where applicable. Every PHI access is audited.

Permissions per role are defined in \`server/auth.js\` (\`PERMS\`). Generated by \`scripts/gen-api-docs.js\`.
`;
for (const [g, list] of Object.entries(groups)) { out += `\n## ${g}\n\n| Method | Path |\n| --- | --- |\n`; for (const x of list) out += `| ${x.method} | \`${x.path}\` |\n`; }
out += `
## Intake payload (Pocket AI)

\`\`\`
POST /api/intake/notes
Authorization: Bearer suds_<key>
Content-Type: application/json

{ "title": "...", "transcript": "...", "summary": "...", "action_items": ["..."], "created_at": "2026-09-10T15:04:00Z", "tags": ["field"] }
\`\`\`

A JSON array or \`{ "notes": [...] }\` is also accepted. Response: \`202 { import_id, staged }\`.

## FHIR R4 API

\`/fhir/R4\` is a read-only FHIR R4 API for the county EHR or an HIE (Patient, EpisodeOfCare, Encounter, Consent, ServiceRequest, Task, Observation, DocumentReference, Organization, Location, HealthcareService, and Bulk Data \`$export\`). It answers in \`application/fhir+json\`, authenticates FHIR clients (created under Settings → FHIR clients, \`/api/admin/fhir-clients\`) with a bearer API key or an OAuth2 client-credentials token from \`POST /fhir/R4/auth/token\`, and returns a client's records only under a live 42 CFR Part 2 consent naming the FHIR client's organisation, recording each disclosure. Endpoints, mappings, scopes and examples: [docs/integration/FHIR.md](integration/FHIR.md).

## Break-glass

Administrators may read a clinical note by sending \`X-Break-Glass-Reason: <reason>\` with \`GET /api/notes/:id\`; the access and reason are written to the audit log.

## Retries and concurrent edits

- **Idempotency-Key** (POST): send a key (1-255 printable characters) and a repeat of the same request by the same user within 24 hours returns the first answer (with \`Idempotent-Replayed: true\`) instead of running again. The same key with a different body is refused with 422. Only successful answers are remembered. Not applied to sign-in, sync, setup or account routes.
- **if_updated_at** (PUT body): the \`updated_at\` of the record as you loaded it. If the record has changed since, the save is refused with \`409 { error, stale: true, updated_at }\` and nothing is written. Omit it to save unconditionally. Successful PUTs return the new \`updated_at\`.
- **Re-admission**: \`POST /api/clients/check-duplicates\` returns \`readmit\` (discharged records outside the caller's caseload that match on surname + date of birth or phone). \`POST /api/clients/:id/readmit { first_name, last_name, dob, phone, reason }\` assigns the caller, opens an episode and queues the event for supervisor review.
`;
fs.writeFileSync(require('node:path').join(__dirname, '..', 'docs', 'API.md'), out);
console.log(`${rows.length} routes documented`);
